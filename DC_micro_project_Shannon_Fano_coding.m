%% ============================================================
%                  COMPRESSION FUNCTION
% =============================================================

function compressText(inputBox)

    % Get input text
    originalText = get(inputBox,'String');

    if isempty(originalText)
        errordlg('Please enter some text!');
        return;
    end

    %% Character frequency

    characters = unique(originalText);

    frequency = zeros(1,length(characters));

    for i = 1:length(characters)
        frequency(i) = sum(originalText == characters(i));
    end

    %% Sort frequency

    [frequency,index] = sort(frequency,'descend');

    characters = characters(index);

    %% Generate Shannon-Fano codes

    codes = cell(1,length(characters));

    for i = 1:length(characters)
        codes{i} = '';
    end

    if length(characters) == 1

        codes{1} = '0';

    else

        codes = shannonFano(...
            frequency,...
            codes,...
            1:length(characters));

    end

    %% Display code table

    tableBox = findobj(gcf,'Style','listbox');

    displayData = {};

    for i = 1:length(characters)

        if characters(i) == ' '
            symbol = '[SPACE]';
        else
            symbol = characters(i);
        end

        displayData{end+1} = sprintf(...
            '%-10s Frequency = %-3d   Code = %s',...
            symbol,...
            frequency(i),...
            codes{i});

    end

    set(tableBox,'String',displayData);

    %% ========================================================
    %                    COMPRESS TEXT
    % =========================================================

    compressedText = '';

    for i = 1:length(originalText)

        position = find(...
            characters == originalText(i),...
            1);

        compressedText = [...
            compressedText codes{position}];

    end

    %% Display compressed text

    compressedBox = findobj(...
        gcf,...
        'Style','edit',...
        '-and',...
        'Enable','inactive');

    set(compressedBox,'String',compressedText);

    %% ========================================================
    %                 COMPRESSION STATISTICS
    % =========================================================

    originalBits = length(originalText) * 8;

    compressedBits = length(compressedText);

    compressionRatio = ...
        originalBits / compressedBits;

    spaceSaved = ...
        ((originalBits-compressedBits) / originalBits) * 100;

    statsBox = findobj(...
        gcf,...
        'Style','text');

    information = sprintf(...
        'Original Size: %d bits     Compressed Size: %d bits     Compression Ratio: %.2f : 1     Space Saved: %.2f %%',...
        originalBits,...
        compressedBits,...
        compressionRatio,...
        spaceSaved);

    set(statsBox(end),'String',information);

    %% ========================================================
    %                     OPEN RECEIVER
    % =========================================================

    createReceiver(...
        originalText,...
        characters,...
        codes,...
        compressedText);

end


%% ============================================================
%                  SHANNON-FANO ALGORITHM
% =============================================================

function codes = shannonFano(frequency,codes,index)

    if length(index) <= 1
        return;
    end

    total = sum(frequency(index));

    cumulative = 0;

    minimumDifference = inf;

    splitPoint = 1;

    for i = 1:length(index)-1

        cumulative = ...
            cumulative + frequency(index(i));

        remaining = total - cumulative;

        difference = ...
            abs(cumulative-remaining);

        if difference < minimumDifference

            minimumDifference = difference;

            splitPoint = i;

        end

    end

    group1 = index(1:splitPoint);

    group2 = index(splitPoint+1:end);

    % First group = 0

    for i = group1
        codes{i} = [codes{i} '0'];
    end

    % Second group = 1

    for i = group2
        codes{i} = [codes{i} '1'];
    end

    % Recursive division

    codes = shannonFano(...
        frequency,...
        codes,...
        group1);

    codes = shannonFano(...
        frequency,...
        codes,...
        group2);

end


