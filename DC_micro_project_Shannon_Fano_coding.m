    %% ========================================================
    %                     DECODE FUNCTION
    % =========================================================

    function decodeText(...
        originalText,...
        characters,...
        codes,...
        compressedText,...
        rx)

        decodedText = '';

        currentCode = '';

        %% Decode binary data

        for k = 1:length(compressedText)

            currentCode = ...
                [currentCode compressedText(k)];

            for j = 1:length(codes)

                if strcmp(...
                        currentCode,...
                        codes{j})

                    decodedText = ...
                        [decodedText characters(j)];

                    currentCode = '';

                    break;

                end

            end

        end

        %% Find output box

        editBoxes = findobj(...
            rx,...
            'Style','edit');

        outputBox = editBoxes(1);

        %% Display decoded text

        set(outputBox,...
            'String',decodedText);

        %% Find status box

        textObjects = findobj(...
          rx,...
            'Style','text');

        statusBox = textObjects(1);

        %% Check transmission

        if strcmp(decodedText,originalText)

            set(statusBox,...
                'String',...
                'STATUS: TRANSMISSION SUCCESSFUL');

        else

            set(statusBox,...
                'String',...
                'STATUS: TRANSMISSION ERROR');

        end

    end
end 
